async function getFilter() {
	var res = await fetch("/api/aliasmanager/filter");

	if (res.status != 200 && res.status != 404) {
		error.innerText = JSON.stringify(res);
		error.parentElement.showModal();
		
		console.error(res);
		return [];
	}
	
	var response = await res.json();

	if (res.status == 404 && response.error.code == "object_not_found_in_padl") {
		error.innerHTML = `Create a <a target="_blank" href="https://faq.infomaniak.com/126">catch-all address</a> first!`;
		error.parentElement.showModal();
		
		console.error(res);
		return [];
	}

	for (var i = 0; i < response.data.scripts.length; i++) {
		var script = response.data.scripts[i];

		if (script.name == "aliasmanagerfilter") {
			var con = script.content
				.replace('# This file is automatically generated by https://github.com/CMD-Golem/TabQ-Website/tree/main/static/aliasmanager\n# It is not intended for manual editing\n\nrequire ["fileinto"];\nif not address :is ["to", "cc"] [', '[')
				.replace('\n] {\n    fileinto "Spam";\n}', ']')
				.replaceAll('\n    ', '');
			var alias_list = JSON.parse(con);
			break;
		}
		else var alias_list = [];
	}

	return alias_list;
}

